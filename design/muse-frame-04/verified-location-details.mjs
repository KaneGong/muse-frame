export function withVerifiedLocationDetails(space){
  const caution=space.id==='reed-path'?'保留湿地浅水而非换成树林；芦苇不能封死路，坐姿只使用已确认的平台木长椅，不另加座椅':space.caution;
  const variants=space.variants.map(variant=>{
    const key=space.id+'.'+variant.id,detail=VERIFIED_LOCATION_DETAILS[key],condition=VERIFIED_SEAT_CONDITIONS[key]?.text;
    const clarified=LOCATION_SCENE_CLARIFICATIONS[key];
    if(!detail&&!condition&&!clarified)return variant;
    const actions=[...variant.actions];
    if(detail&&!actions.includes('sit'))actions.splice(Math.min(1,actions.length),0,'sit');
    const support={...variant.support};
    if(detail)support.sit=detail.sitSupport;
    if(condition&&support.sit)support.sit+='；'+condition;
    const scene=[clarified||variant.scene,detail?.sceneAddition].filter(Boolean).join('；');
    return {...variant,sourceScene:variant.sourceScene||variant.scene,scene,actions,support,seat:detail?.seat||variant.seat,seatCondition:condition||'',caution:[variant.caution||caution,condition].filter(Boolean).join('；'),visualCalibration:detail?{imageFile:detail.imageFile,imageSha256:detail.imageSha256,reviewedAt:detail.reviewedAt}:variant.visualCalibration};
  });
  const actions=[...new Set(variants.flatMap(variant=>variant.actions))];
  const support={...space.support};if(actions.includes('sit'))support.sit='只使用所选背景中已确认的具体座位';
  const subject=space.id==='newsstand'?'人物位于报刊亭旁的站位或已有长椅，保留刊架与街树的生活信息':space.subject;
  return {...space,variants,actions,support,subject,caution};
}
