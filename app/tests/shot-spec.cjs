const test=require('node:test'),assert=require('node:assert/strict');
const S=require('../static/shot-spec.js'),lib=require('../static/library.json');
const refs={face:'f',body:'b',outfit:'o',scene:'e'},assets=['f','b','o','e','p1','p2'].map(id=>({id}));
const ctx={refs,assets,bodyFromFace:false,library:lib};
test('neutral new project emits no unselected pose, framing or photographic treatment',()=>{
 const s=S.create(),r=S.compile(s,'s1',ctx);
 assert.doesNotMatch(r.prompt,/冷蓝|微笑|站立|全身|前景|仰拍|右侧|光线：|摄影处理：/);
 assert.match(r.prompt,/图1/);assert.match(r.prompt,/图3/);assert.match(r.prompt,/一张连续/);
});
test('shared settings follow project but shot overrides and explicit clears survive changes',()=>{
 const s=S.create();S.addShot(s,'s2');S.setField(s,'s1','color','中性','project',lib);S.setField(s,'s2','color','黑白','shot',lib);
 S.setField(s,'s1','weather','','shot',lib);S.setField(s,'s1','weather','雨后','project',lib);
 assert.equal(S.effective(s,'s1').fields.color,'中性');assert.equal(S.effective(s,'s2').fields.color,'黑白');assert.equal(S.effective(s,'s1').fields.weather,'');
});
test('changing style preserves explicit adjustments and reset restores preset defaults',()=>{
 const s=S.create(),a=lib.styles[0],b=lib.styles[1];
 S.setField(s,'s1','style',a.id,'project',lib);S.setField(s,'s1','light','侧面硬光','project',lib);S.setField(s,'s1','style',b.id,'project',lib);
 assert.equal(S.effective(s,'s1').fields.light,'侧面硬光');assert.equal(S.effective(s,'s1').fields.color,b.parts.color);
 S.resetStyle(s,'s1','project');assert.equal(S.effective(s,'s1').fields.light,b.parts.light);
});
test('clearing a preset component remains clear across style change',()=>{
 const s=S.create();S.setField(s,'s1','style',lib.styles[0].id,'project',lib);S.setField(s,'s1','light','','project',lib);S.setField(s,'s1','style',lib.styles[1].id,'project',lib);
 assert.equal(S.effective(s,'s1').fields.light,'');assert.doesNotMatch(S.compile(s,'s1',ctx).prompt,/光线：/);
});
test('pose image and natural or strict policy belong to each shot',()=>{
 const s=S.create();S.addShot(s,'s2');S.setPose(s,'s1',{source:'reference',assetId:'p1',text:'坐姿',adherence:'natural'});S.setPose(s,'s2',{source:'reference',assetId:'p2',text:'站姿',adherence:'strict'});
 const a=S.compile(s,'s1',ctx),b=S.compile(s,'s2',ctx);assert.equal(a.referenceRoles.pose,'p1');assert.equal(b.referenceRoles.pose,'p2');assert.match(a.prompt,/自然调整/);assert.match(b.prompt,/关节/);
 assert.doesNotMatch(a.prompt,/完全照抄/);
});
test('removing scene recalculates pose slot without stale image5',()=>{
 const s=S.create();S.setPose(s,'s1',{source:'reference',assetId:'p1',adherence:'natural'});assert.match(S.compile(s,'s1',ctx).prompt,/图5/);
 const r=S.compile(s,'s1',{...ctx,refs:{...refs,scene:''}});assert.doesNotMatch(r.prompt,/图5/);assert.match(r.prompt,/图4/);
});
test('half body does not inherit full outfit visibility or foot framing',()=>{
 const s=S.create();S.setField(s,'s1','shot','腰部以上半身取景','shot',lib);
 const r=S.compile(s,'s1',ctx);assert.match(r.prompt,/腰部以上/);assert.doesNotMatch(r.prompt,/完整鞋脚|鞋包.*可见|全身入镜/);
});
test('face fallback does not claim full body measurements',()=>{
 const r=S.compile(S.create(),'s1',{...ctx,refs:{face:'f',outfit:'o'},bodyFromFace:true});
 assert.doesNotMatch(r.prompt,/身高|腿身比|锁定图2/);assert.match(r.prompt,/无独立身形/);
});
test('user prose and manual draft are not silently regenerated by options',()=>{
 const s=S.create();s.project.notes='保留手袋。';S.setMode(s,'s1','manual',ctx);S.shot(s,'s1').manualText='My own photography request.';
 S.setField(s,'s1','color','黑白','project',lib);assert.equal(S.compile(s,'s1',ctx).prompt,'My own photography request.');
 S.setMode(s,'s1','guided',ctx);assert.match(S.compile(s,'s1',ctx).prompt,/保留手袋/);assert.equal(S.shot(s,'s1').manualText,'My own photography request.');
});
test('manual reference remapping requires explicit review and never edits prose',()=>{
 const s=S.create();S.setMode(s,'s1','manual',ctx);const text=S.compile(s,'s1',ctx).prompt;
 const changed={...ctx,refs:{...refs,scene:''}};const r=S.compile(s,'s1',changed);assert.equal(r.prompt,text);assert.equal(r.needsReferenceReview,true);
 S.reviewReferences(s,'s1',changed);assert.equal(S.compile(s,'s1',changed).needsReferenceReview,false);
});
test('serialized state compiles deterministically and preserves source ownership',()=>{
 const s=S.create();S.setField(s,'s1','shot','腰部以上半身取景','shot',lib);const before=JSON.stringify(s),a=S.compile(s,'s1',ctx);
 assert.equal(JSON.stringify(s),before);assert.deepEqual(S.compile(JSON.parse(before),'s1',ctx),a);
 assert.equal(S.effective(s,'s1').sources.shot,'shot');
});
test('personalized structured style has one effective light and permits clearing it',()=>{
 const s=S.create();S.setField(s,'s1','style','自定义肖像；光线：窗边柔光；色调：暖色','project',lib);S.setField(s,'s1','light','侧面硬光','project',lib);
 let p=S.compile(s,'s1',ctx).prompt;assert.equal((p.match(/^光照：/gm)||[]).length,1);assert.doesNotMatch(p,/窗边柔光/);
 S.setField(s,'s1','light','','project',lib);assert.doesNotMatch(S.compile(s,'s1',ctx).prompt,/^光照：|窗边柔光/m);
});
